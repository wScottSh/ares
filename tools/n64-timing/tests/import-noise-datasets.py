#!/usr/bin/env python3
"""Writes noise-datasets.hpp from Thar0/RDP-Noise rdp_noise_lfsr.c (Unlicense, e7f6c7f).

usage: import-noise-datasets.py <RDP-Noise>/rdp_noise_lfsr.c
Reads the C source as text; nothing from the clone runs.
"""
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text()


def block(name):
    return re.search(name + r"[^=]*=\s*\{(.*?)\n\};", source, re.S).group(1)


def bits(text):
    return "".join("x" if int(v) < 0 else v for v in re.findall(r"-?\d+", text))


sets = {"A": bits(block("A_dataset")), "B": bits(block("B_dataset"))}
for i, c in enumerate(re.findall(r"\{(.*?)\}", block("C_datasets"), re.S)):
    sets[f"C{i}"] = bits(c)
assert all(len(v) == 1016 for v in sets.values()), {k: len(v) for k, v in sets.items()}

lines = [
    "//GENERATED by tools/n64-timing/tests/import-noise-datasets.py. Do not edit.",
    "//Thar0/RDP-Noise e7f6c7f rdp_noise_lfsr.c (Unlicense, public domain): the a, b",
    "//and c bits of 1016-px 1-cycle NOISE rectangles dumped on a console; x is a c",
    "//bit the combiner clamp hid (a = 1).",
    "",
]
for name, value in sets.items():
    lines.append(f"static const char Noise{name}[] =")
    lines += [f'  "{value[i:i + 72]}"' for i in range(0, len(value), 72)]
    lines[-1] += ";"
Path(__file__).with_name("noise-datasets.hpp").write_text("\n".join(lines) + "\n")
